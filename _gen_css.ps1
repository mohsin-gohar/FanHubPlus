function Get-SizeVal([string]$v) {
    if ($v -eq 'full') { return '100%' }
    if ($v -eq 'screen') { return '100vh' }
    if ($v -eq 'auto') { return 'auto' }
    if ($v -match '^n(\d+(?:\.\d+)?)$') { return '-' + $Matches[1] + '%' }
    if ($v -match '^(\d+(?:\.\d+)?)$') { return $Matches[1] + 'px' }
    return $null
}
function Get-GColVal([string]$slug) {
    $map = @{
        'repeat-2' = 'repeat(2, minmax(0, 1fr))'
        'repeat-3' = 'repeat(3, minmax(0, 1fr))'
        'repeat-4' = 'repeat(4, minmax(0, 1fr))'
        'repeat-5' = 'repeat(5, minmax(0, 1fr))'
        'repeat-6' = 'repeat(6, minmax(0, 1fr))'
    }
    if ($map.ContainsKey($slug)) { return $map[$slug] }
    return $null
}
function Get-PropVal([string]$prop, [string]$v) {
    if ($v -eq 'full')  { return '100%' }
    if ($v -eq 'screen'){ return '100vh' }
    if ($v -eq 'auto')  { return 'auto' }
