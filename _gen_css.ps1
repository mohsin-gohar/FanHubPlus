# token -> CSS declaration.  Returns $null when the token needs a bespoke rule.
function Resolve-Decl([string]$cls) {
    if (-not $cls.StartsWith('fhp-')) { return $null }
    $b = $cls.Substring(4)
    $accent = $false
    if ($b.StartsWith('accent-')) { $accent = $true; $b = $b.Substring(7) }

    # ---------- colours ----------
    if ($b -match '^text-(.+)$')  { $d = Get-ColorDecl $Matches[1] $(if($accent){'accent-color'}else{'color'}); if ($d) { return $d } }
    if ($b -match '^bg-(.+)$')    { $d = Get-ColorDecl $Matches[1] $(if($accent){'accent-color'}else{'background-color'}); if ($d) { return $d } }
    if ($b -match '^borderc-(.+)$'){ $d = Get-ColorDecl $Matches[1] 'border-color'; if ($d) { return $d } }
    if ($b -match '^border-(.+)$') { $d = Get-ColorDecl $Matches[1] 'border-color'; if ($d) { return $d } }

    # ---------- font-size / letter-spacing ----------
    if ($b -match '^fs-(\d+(?:\.\d+)?)$')        { return "font-size: $($Matches[1])px;" }
    if ($b -match '^tracking-(\d+)-(\d+)em$')    { return "letter-spacing: 0.$($Matches[1])$($Matches[2])em;" }
    if ($b -match '^ls-(\w+)$') {
        $ls = @{ wide='.025em'; wider='.05em'; widest='.1em'; tight='-.025em'; tighter='-.05em'; normal='normal' }
        if ($ls.ContainsKey($Matches[1])) { return "letter-spacing: $($ls[$Matches[1]]);" }
    }

    # ---------- radius / border width ----------
    if ($b -match '^r([a-z]{1,2})-(\d+(?:\.\d+)?)$') {
        $mm = @{
            t='top'; b='bottom'; l='left'; r='right'
            tb='top bottom'; lr='left right'; tl='top left'; tr='top right'
            bl='bottom left'; br='bottom right'; ss='top left'; ee='bottom right'
        }
        $k = $Matches[1]
        if ($mm.ContainsKey($k)) { return "border-$($mm[$k])-radius: $($Matches[2])px;" }
    }
    if ($b -match '^r-(\d+(?:\.\d+)?)$') { return "border-radius: $($Matches[1])px;" }
    if ($b -match '^bw-(\d+(?:\.\d+)?)$')  { return "border-width: $($Matches[1])px;" }
    if ($b -eq 'border-dashed') { return 'border-style: dashed;' }
    if ($b -eq 'border-dotted') { return 'border-style: dotted;' }
    if ($b -eq 'border-solid')  { return 'border-style: solid;' }
    if ($b -eq 'border-none')   { return 'border-style: none;' }

    # ---------- spacing & sizing ----------
    if ($b -match '^(m|mt|mb|ml|mr|mx|my|p|pt|pb|pl|pr|px|py|w|h|minw|maxw|minh|maxh|top|bottom|left|right|inset|z|gap|gapx|gapy)-(.+)$') {
        $k = $Matches[1]; $v = $Matches[2]
        $val = Get-PropVal $k $v
        if ($null -ne $val -and $PM.ContainsKey($k)) {
            if ($k -eq 'z') { return "z-index: $val;" }
            return "$($PM[$k]): $val;"
        }
    }

    # ---------- aspect ratio / grid ----------
    if ($b -match '^aspect-(\d+)-(\d+)$') { return "aspect-ratio: $($Matches[1]) / $($Matches[2]);" }
    if ($b -eq 'aspect-square') { return 'aspect-ratio: 1 / 1;' }
    if ($b -eq 'aspect-wide')   { return 'aspect-ratio: 16 / 9;' }
    if ($b -eq 'aspect-tall')   { return 'aspect-ratio: 4 / 5;' }
    if ($b -match '^gcol-(.+)$') { $g = Get-GColVal $Matches[1]; if ($g) { return "grid-template-columns: $g;" } }
    if ($b -match '^gspan-(\d+)$') { return "grid-column: span $($Matches[1]) / span $($Matches[1]);" }
    if ($b -eq 'gspan-full') { return 'grid-column: 1 / -1;' }
    if ($b -match '^gcol-(\d+)$')  { return "grid-template-columns: repeat($($Matches[1]), minmax(0, 1fr));" }

    # ---------- translate ----------
    if ($b -match '^t([xy])-(n?)(\d+(?:\.\d+)?)$') {
        $ax = $Matches[1]; $sg = if ($Matches[2]) { '-' } else { '' }; $n = $Matches[3]
        return "--fhp-t$ax`: $sg$n%;`ntransform: translate(var(--fhp-tx, 0), var(--fhp-ty, 0));"
    }
    # ---------- transform family ----------
    if ($b -eq 'transform')      { return 'transform: translate(var(--fhp-tx, 0), var(--fhp-ty, 0));' }
    if ($b -eq 'transform-none') { return 'transform: none;' }
    if ($b -eq 'transform-gpu')  { return 'transform: translateZ(0);' }
    if ($b -eq 'transform-cpu')  { return 'transform: translateZ(0);' }
    if ($b -match '^origin-(\w+)$')   { return "transform-origin: $($Matches[1]);" }
    if ($b -match '^rotate-(\d+)$')    { return "transform: translate(var(--fhp-tx,0),var(--fhp-ty,0)) rotate($($Matches[1])deg);" }
    if ($b -match '^nrotate-(\d+)$')   { return "transform: translate(var(--fhp-tx,0),var(--fhp-ty,0)) rotate(-$($Matches[1])deg);" }
    if ($b -match '^scale-(\d+(?:\.\d+)?)$') { return "transform: translate(var(--fhp-tx,0),var(--fhp-ty,0)) scale($($Matches[1]));" }
    # ---------- transition ----------
    $TP = 'transition-property: all; transition-timing-function: cubic-bezier(.4,0,.2,1); transition-duration: 300ms;'
    if ($b -eq 'transition') { return $TP }
    if ($b -match '^transition-(all|colors|opacity|transform|shadow|none|filter)$') { return "transition-property: $($Matches[1]); transition-timing-function: cubic-bezier(.4,0,.2,1); transition-duration: 300ms;" }
    if ($b -match '^dur(\d+)$') { return "transition-duration: $($Matches[1])ms;" }
    if ($b -eq 'delay-0')       { return 'transition-delay: 0ms;' }
    if ($b -match '^delay-(\d+)$'){ return "transition-delay: $($Matches[1])ms;" }
    if ($b -match '^ease-(in|out|inout|linear|initial)$') { return 'transition-timing-function: cubic-bezier(.4,0,.2,1);' }
    if ($b -match '^ease-(in|out|inout)$') { return "transition-timing-function: cubic-bezier(.4,0,.2,1);" }
    # ---------- effects ----------
    if ($b -match '^backdrop-blur(.*)$') { return '-webkit-backdrop-filter: blur(8px); backdrop-filter: blur(8px);' }
    if ($b -match '^shadow-(.+)$') {
        $sh = @{
            'sm'='0 1px 2px rgba(0,0,0,.06)'; 'md'='0 4px 10px rgba(0,0,0,.08)'
            'lg'='0 10px 30px rgba(0,0,0,.12)'; 'xl'='0 20px 50px rgba(0,0,0,.16)'
            '2xl'='0 30px 80px rgba(0,0,0,.20)'; 'inner'='inset 0 2px 4px rgba(0,0,0,.08)'
        }
        if ($sh.ContainsKey($Matches[1])) { return "box-shadow: $($sh[$Matches[1]]);" }
    }
    if ($b -match '^weight-(\d+)$') { return "font-weight: $($Matches[1]);" }
    if ($b -match '^leading-(\d+(?:\.\d+)?)$') { return "line-height: $($Matches[1]);" }
    if ($b -match '^opacity-(\d+(?:\.\d+)?)$') { return "opacity: $($Matches[1]);" }

    # ---------- named singles ----------
    $N = @{
        'cursor-pointer'='cursor: pointer;'; 'cursor-not-allowed'='cursor: not-allowed;'
        'cursor-default'='cursor: default;'; 'cursor-grab'='cursor: grab;'
        'cursor-grabbing'='cursor: grabbing;'; 'cursor-wait'='cursor: wait;'
        'cursor-help'='cursor: help;'; 'cursor-text'='cursor: text;'
        'cursor-move'='cursor: move;'; 'cursor-crosshair'='cursor: crosshair;'
        'cursor-cell'='cursor: cell;'; 'cursor-copy'='cursor: copy;'
        'cursor-alias'='cursor: alias;'; 'cursor-progress'='cursor: progress;'
        'cursor-zoom-in'='cursor: zoom-in;'; 'cursor-zoom-out'='cursor: zoom-out;'
        'select-none'='user-select: none;'; 'select-text'='user-select: text;'
        'select-all'='user-select: all;'; 'select-auto'='user-select: auto;'
        'pointer-events-none'='pointer-events: none;'; 'pointer-events-auto'='pointer-events: auto;'
        'resize-none'='resize: none;'; 'resize-both'='resize: both;'
        'resize'='resize: both;'; 'resize-x'='resize: horizontal;'
        'resize-y'='resize: vertical;'
        'appearance-none'='appearance: none;'; 'list-none'='list-style: none;'
        'list-disc'='list-style-type: disc;'; 'list-decimal'='list-style-type: decimal;'
        'underline'='text-decoration: underline;'; 'overline'='text-decoration: overline;'
        'line-through'='text-decoration: line-through;'; 'no-underline'='text-decoration: none;'
        'uppercase'='text-transform: uppercase;'; 'lowercase'='text-transform: lowercase;'
        'capitalize'='text-transform: capitalize;'; 'normal-case'='text-transform: none;'
        'align-start'='vertical-align: top;'; 'align-end'='vertical-align: bottom;'
        'align-center'='vertical-align: middle;'; 'align-baseline'='vertical-align: baseline;'
        'align-top'='vertical-align: top;'; 'align-bottom'='vertical-align: bottom;'
        'flex-row'='flex-direction: row;'; 'flex-row-reverse'='flex-direction: row-reverse;'
        'flex-col'='flex-direction: column;'; 'flex-col-reverse'='flex-direction: column-reverse;'
