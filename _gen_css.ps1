# logical-property tokens that need the state wrapper rather than a plain rule
function Resolve-Logical([string]$st, [string]$inner) {
    if ($st -eq 'last') {
        if ($inner -eq 'mb-0')  { return 'margin-bottom: 0;' }
        if ($inner -eq 'mt-0')  { return 'margin-top: 0;' }
        if ($inner -match '^mb-(\d+)px$') { return "margin-bottom: $($Matches[1])px;" }
    }
    $lm = @{
        'start-0'      = 'inset-inline-start: 0;'
        'end-0'        = 'inset-inline-end: 0;'
        'text-start'   = 'text-align: start;'
        'text-end'     = 'text-align: end;'
        'border-start' = 'border-inline-start: 1px solid;'
        'border-end'   = 'border-inline-end: 1px solid;'
        'ml-5px'       = 'margin-inline-start: 5px;'
        'mr-5px'       = 'margin-inline-end: 5px;'
        'ms-5px'       = 'margin-inline-start: 5px;'
        'me-5px'       = 'margin-inline-end: 5px;'
    }
    if ($lm.ContainsKey($inner)) { return $lm[$inner] }
    if ($inner -match '^([mp][lrsexy])-(\d+)px$') {
        $mp = @{
            'ml'='margin-inline-start'; 'mr'='margin-inline-end'
            'ms'='margin-inline-start'; 'me'='margin-inline-end'
            'pl'='padding-inline-start'; 'pr'='padding-inline-end'
            'ps'='padding-inline-start'; 'pe'='padding-inline-end'
        }
        return "$($mp[$Matches[1]]): $($Matches[2])px;"
    }
    if ($inner -match '^(left|right)-(\d+)px$') {
        $lp = if ($Matches[1] -eq 'left') { 'inset-inline-start' } else { 'inset-inline-end' }
        return "$lp`: $($Matches[2])px;"
    }
    if ($inner -match '^(left|right)-auto$') {
        $lp = if ($Matches[1] -eq 'left') { 'inset-inline-start' } else { 'inset-inline-end' }
        return "$lp`: auto;"
    }
    if ($inner -eq 'text-decoration-underline') { return 'text-decoration: underline;' }
    if ($inner -match '^scale-x-(\d+)$') { return "transform: translate(var(--fhp-tx,0),var(--fhp-ty,0)) scaleX($($Matches[1]));" }
    if ($inner -match '^scale-y-(\d+)$') { return "transform: translate(var(--fhp-tx,0),var(--fhp-ty,0)) scaleY($($Matches[1]));" }
    return $null
}

