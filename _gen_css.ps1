# "white-60" -> rgba(255,255,255,.6)   |   "primary-30" -> rgba(var, .3)
function Get-ColorDecl([string]$v, [string]$prop) {
    $alpha = $null
    if ($v -match '^(?<n>.+?)-(?<a>\d+)$' -and $KnownColor.ContainsKey($Matches['n'])) {
        $alpha = [double]$Matches['a']
        $v = $Matches['n']
    }
    if ($KnownColor.ContainsKey($v)) { $hex = $KnownColor[$v] }
    elseif ($v -match '^#([0-9a-fA-F]{3})$')   { $hex = '#' + $Matches[1] }
    elseif ($v -match '^#([0-9a-fA-F]{6})$')   { $hex = '#' + $Matches[1] }
    elseif ($v -match '^[0-9a-fA-F]{3}$')      { $hex = '#' + $v }
    elseif ($v -match '^[0-9a-fA-F]{6}$')      { $hex = '#' + $v }
    else { return $null }
    $final = $hex
    if ($null -ne $alpha) {
        $al = [math]::Round($alpha / 100, 3)
        if ($hex -match '^#([0-9a-fA-F]{6})$') {
            $h = $Matches[1]
            $r2 = [Convert]::ToInt32($h.Substring(0,2),16)
            $g2 = [Convert]::ToInt32($h.Substring(2,2),16)
            $b2 = [Convert]::ToInt32($h.Substring(4,2),16)
            $final = "rgba($r2, $g2, $b2, $al)"
        } else {
            $final = "color-mix(in srgb, $hex $([int]$alpha)%, transparent)"
        }
    }
    if ($prop) { return "$prop`: $final;" }
    return $final
}

