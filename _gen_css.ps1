    if ($b -match '^leading-(\d+)-(\d+)$') { return "line-height: $([double]$Matches[1] / [double]$Matches[2]);" }
    if ($b -match '^font-(primary|secondary|body|muted|mono)$') {
        $ff = @{
            primary='var(--fhp-font-primary)'; secondary='var(--fhp-font-secondary)'
            body='var(--fhp-body-font)'; muted='var(--fhp-muted-font)'; mono='var(--fhp-font-mono)'
        }
        return "font-family: $($ff[$Matches[1]]);"
    }
    if ($b -eq 'spin')          { return 'animation: fhp-spin 1s linear infinite;' }
    if ($b -eq 'pulse')         { return 'animation: fhp-pulse 2s ease-in-out infinite;' }
    if ($b -eq 'ping')          { return 'animation: fhp-ping 1s cubic-bezier(0,0,.2,1) infinite;' }
    if ($b -eq 'bounce')        { return 'animation: fhp-bounce 1s infinite;' }
    if ($b -eq 'ease')          { return 'transition-timing-function: cubic-bezier(.4,0,.2,1);' }
    if ($b -eq 'rotate-me')     { return 'animation: fhp-rotateme 12s linear infinite;' }
    if ($b -eq 'rotateme')      { return 'animation: fhp-rotateme 12s linear infinite;' }
    if ($b -eq 'text-animation'){ return 'animation: fhp-texteffect 4s ease-in-out infinite;' }
    if ($b -eq 'is-active-cat') { return 'color: var(--bs-primary); font-weight: 700;' }
    if ($b -eq 'is-active-state') { return 'opacity: 1; visibility: visible;' }
    if ($b -eq 'is')            { return $null }     # polymorphic JS hook
    if ($b -eq 'group')         { return $null }     # JS hook: marks the group-hover parent
    if ($b -eq 'admin-nav')     { return $null }     # JS hook toggled by the admin shell
    if ($b -eq 'share')         { return $null }     # JS hook for the share button
    if ($b -eq 'with-border')   { return 'border: 1px solid var(--fhp-body, #1d2433);' }
    if ($b -eq 'backdrop')      { return 'backdrop-filter: blur(10px); -webkit-backdrop-filter: blur(10px);' }
    if ($b -eq 'scrollbar')     { return 'scrollbar-width: thin; scrollbar-color: var(--fhp-scroll-thumb, #c9cedb) transparent;' }
    if ($b -eq 'd-block')       { return 'display: block;' }
    if ($b -eq 'justify-start') { return 'justify-content: flex-start;' }
    if ($b -eq 'mx-auto')       { return 'margin-inline: auto;' }
    if ($b -eq 'mx-0')          { return 'margin-inline: 0;' }
    if ($b -eq 'mb-0')          { return 'margin-bottom: 0;' }
    if ($b -eq 'mt-0')          { return 'margin-top: 0;' }
    if ($b -eq 'h-100')         { return 'height: 100%;' }

    # ---------- late / direct cases ----------
    if ($accent) { $d = Get-ColorDecl $b $null; if ($d) { return "accent-color: $d;" } }
    if ($b -match '^border-(t|b|s|e|r|l|ss|ee)-(.+)$') {
        $mm = @{ t='top'; b='bottom'; s='left'; e='right'; r='right'; l='left'; ss='left'; ee='right' }
        $d = Get-ColorDecl $Matches[2] $null
        if ($d) { return "border-$($mm[$Matches[1]])-color: $d;" }
    }
    if ($b -match '^[01]px$')            { return "$(if($b -eq '1px'){'1px'}else{'0'});" }
    if ($b -match '^(top|bottom|left|right|inset)-(\d+)(px|rem|em|%)?$') {
        $mm = @{ top='top'; bottom='bottom'; left='left'; right='right'; inset='inset' }
        $u = if ($Matches[3]) { $Matches[3] } else { 'px' }
        return "$($mm[$Matches[1]]): $($Matches[2])$u;"
    }
    if ($b -match '^(h|w|minh|minw|maxh|maxw)-(\d+)(px|rem|%)?$') {
        $mm = @{ h='height'; w='width'; minh='min-height'; minw='min-width'; maxh='max-height'; maxw='max-width' }
        $u = if ($Matches[3]) { $Matches[3] } else { 'px' }
        return "$($mm[$Matches[1]]): $($Matches[2])$u;"
    }
    if ($b -match '^r-(rb|tl|tr|bl|br|lr)-(\d+(?:\.\d+)?)$') {
        $mm = @{ rb='bottom'; tr='top right'; tl='top left'; bl='bottom left'; br='bottom right'; lr='left' }
        return "border-$($mm[$Matches[1]])-radius: $($Matches[2])px;"
    }
    if ($b -match '^r-(rb|tl|tr|bl|br|lr|t|b)-(\d+(?:\.\d+)?)$') {
        $mm = @{ rb='bottom'; tr='top right'; tl='top left'; bl='bottom left'
                 br='bottom right'; lr='left'; t='top'; b='bottom' }
        return "border-$($mm[$Matches[1]])-radius: $($Matches[2])px;"
    }
    if ($b -eq 'translate-y-full') { return 'transform: translateY(100%);' }
    if ($b -eq 'translate-y-0')    { return 'transform: translateY(0);' }
    if ($b -match '^translate-y-(\d+)$') { return "transform: translateY($($Matches[1])px);" }
    if ($b -eq 'translate-x-full') { return 'transform: translateX(100%);' }

    if ($b -eq 'group')     { return $null }     # JS hook only, no styling
    if ($b -match '^(nav|admin-nav|nav__dropdown|nav__searchbox|share|num)$') { return $null }
    if ($b -match '^pill--') { return $null }     # markup artefact
    if ($b -eq 'bg-url')    { return $null }     # url() is inline in the markup
    return $null
}

