    if ($v -eq '0')     { return '0' }
    if ($v -match '^n(\d+(?:\.\d+)?)$') { return '-' + $Matches[1] + 'px' }
    if ($v -match '^(\d+(?:\.\d+)?)pct$') { return $Matches[1] + '%' }
    if ($v -match '^(\d+(?:\.\d+)?)$')  { return $Matches[1] + 'px' }
    return $null
}

